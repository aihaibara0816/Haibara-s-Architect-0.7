"""Archive HAF 0.2, retaining the previous source archive and immutable runs."""
from pathlib import Path
import hashlib,json,zipfile

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'releases/0.2/deliverables'
OVERLAYS=['README.md','CHANGELOG.md','AGENTS.md','agent_config.json','hafusion/__init__.py','tools/agent.py','learning/README.md',
          'tools/release_0_2_docs.py','tools/release_0_2_report.py','tools/release_0_2_package.py']

def sha(data):return hashlib.sha256(data).hexdigest()
def main():
    OUT.mkdir(parents=True,exist_ok=True)
    base=ROOT/'cases/guangzhou_ctf/experiments/detail_v2/deliverables/HAF_CTF_Detail_Study_Source.zip'
    files={}
    if base.exists():
        with zipfile.ZipFile(base) as z:
            for name in z.namelist():
                if not name.startswith('HAF_Mainline/') or name.endswith('/'):continue
                rel=name[len('HAF_Mainline/'):]
                if rel not in ['SOURCE_INVENTORY.json','ARCHIVE_SCOPE.txt']:files[rel]=z.read(name)
        parent={'filename':base.name,'sha256':sha(base.read_bytes()),'preserved_member_count':len(files)}
    else:
        inventory=json.loads((ROOT/'SOURCE_INVENTORY.json').read_text())
        for row in inventory:
            p=ROOT/row['path']
            if not p.is_file():raise FileNotFoundError(p)
            files[row['path']]=p.read_bytes()
        parent={'repack_from':'SOURCE_INVENTORY.json','preserved_member_count':len(files)}
    for rel in OVERLAYS:files[rel]=(ROOT/rel).read_bytes()
    # The older source snapshot deliberately contained only a minimal Shenzhen
    # baseline. Include every new catalog reference so the release is auditable
    # without the original working directory.
    catalog=json.loads((ROOT/'docs/haf_0_2_capabilities.json').read_text())
    for item in catalog['capabilities']:
        for key in ['implementation','consumers','evidence']:
            for rel in item[key]:
                if rel not in files:files[rel]=(ROOT/rel).read_bytes()
    for folder in ['docs','history/pre_haf_0_2','releases/0.2']:
        for p in (ROOT/folder).rglob('*'):
            if not p.is_file() or '__pycache__' in p.parts:continue
            if p.name.endswith('.zip') or p.name in ['delivery_manifest.json','upload_result.json']:continue
            if any(part.endswith('_helpers') for part in p.parts):continue
            files[str(p.relative_to(ROOT))]=p.read_bytes()
    scope="""HAF 0.2 code and documentation, based on the previously delivered CTF detail-study source.
Includes every original source member (with explicitly versioned metadata/entrypoint overlays), HA0.3 dependencies, CTF V1 and local experiments, Shenzhen V2 baseline, source photos/research, tests and preserved rejected experiments.
Does not duplicate the complete Canton V5/HA0.3 original distribution ZIPs or original Canton SKP history; retain those separate archives.
No new full building generated by this release. CTF detail_v2 is a local study, not an accepted CTF V2.
No downloaded/imported CTF SU mesh is present. No Minecraft game acceptance was performed.
The three personal Skills are saved separately, not installed by extracting this engineering archive.
Photographs retain their original rights and source notes. Existing source attributions and licenses are retained.
Workspace folder names and historical 0.1 replay labels are not silently relabeled as new algorithms.
"""
    files['ARCHIVE_SCOPE.txt']=scope.encode()
    files['RELEASE_PARENT.json']=json.dumps(parent,indent=2).encode()
    inventory=[dict(path=rel,bytes=len(data),sha256=sha(data)) for rel,data in sorted(files.items()) if rel!='SOURCE_INVENTORY.json']
    files['SOURCE_INVENTORY.json']=(json.dumps(inventory,ensure_ascii=False,indent=2)+'\n').encode()
    target=OUT/'HAF_0.2_Source.zip'
    with zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for rel,data in sorted(files.items()):z.writestr('HAF-0.2/'+rel,data)
    with zipfile.ZipFile(target) as z:assert z.testzip() is None
    manifest={'engine_version':'0.2.0','archive_root':'HAF-0.2','members':len(files),'zip_crc':'pass','parent':parent,
              'files':[dict(filename=p.name,bytes=p.stat().st_size,sha256=sha(p.read_bytes())) for p in [OUT/'HAF_0.2_Skills_Workflow.html',target]]}
    (ROOT/'releases/0.2/delivery_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'archive':target.name,'members':len(files),'bytes':target.stat().st_size,'sha256':sha(target.read_bytes())}))

if __name__=='__main__':main()
